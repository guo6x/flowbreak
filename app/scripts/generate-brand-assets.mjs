// All launcher / splash / browser assets are derived from this one SVG.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import sharp from 'sharp';

const root = fileURLToPath(new URL('..', import.meta.url));
const check = process.argv.includes('--check');
const svg = await readFile(path.join(root, 'src/assets/icon.svg'), 'utf8');
const background = svg.match(/<rect[^>]+fill="(#[0-9A-Fa-f]{6})"/)?.[1];
const paths = [...svg.matchAll(/<path d="([^"]+)" fill="(#[0-9A-Fa-f]{6})"\s*\/>/g)];
if (!background || paths.length !== 2) throw new Error('Brand source must contain a background and two flow shapes.');
const shapes = paths.map(([, d, fill]) => `<path d="${d}" fill="${fill}"/>`).join('');
const foreground = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108"><g transform="translate(22 22)">${shapes}</g></svg>`;
const output = new Map();
output.set('public/brand-mark.svg', Buffer.from(svg));
for (const [file, size] of [['public/favicon.png', 48], ['public/icon-192.png', 192], ['public/icon-512.png', 512]]) {
  output.set(file, await sharp(Buffer.from(svg)).resize(size, size).png().toBuffer());
}
const res = 'android/app/src/main/res';
for (const [density, size] of [['mdpi', 48], ['hdpi', 72], ['xhdpi', 96], ['xxhdpi', 144], ['xxxhdpi', 192]]) {
  const raster = await sharp(Buffer.from(svg)).resize(size, size).png().toBuffer();
  output.set(`${res}/mipmap-${density}/ic_launcher.png`, raster);
  const circle = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><circle cx="32" cy="32" r="32" fill="${background}"/>${shapes}</svg>`;
  output.set(`${res}/mipmap-${density}/ic_launcher_round.png`, await sharp(Buffer.from(circle)).resize(size, size).png().toBuffer());
  const adaptiveSize = Math.round(size * 108 / 48);
  output.set(`${res}/mipmap-${density}/ic_launcher_foreground.png`, await sharp(Buffer.from(foreground)).resize(adaptiveSize, adaptiveSize).png().toBuffer());
}
const vector = (monochrome = false) => `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/generate-brand-assets.mjs. Edit src/assets/icon.svg. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n  <group android:translateX="22" android:translateY="22">\n${paths.map(([, d, fill]) => `    <path android:pathData="${d}" android:fillColor="${monochrome ? '#FFFFFF' : fill}"/>`).join('\n')}\n  </group>\n</vector>\n`;
output.set(`${res}/drawable-v24/ic_launcher_foreground.xml`, Buffer.from(vector()));
output.set(`${res}/drawable/ic_launcher_monochrome.xml`, Buffer.from(vector(true)));
output.set(`${res}/drawable/ic_launcher_background.xml`, Buffer.from(`<?xml version="1.0" encoding="utf-8"?>\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108"><path android:fillColor="${background}" android:pathData="M0,0h108v108h-108z"/></vector>\n`));
output.set(`${res}/values/ic_launcher_background.xml`, Buffer.from(`<?xml version="1.0" encoding="utf-8"?>\n<resources><color name="ic_launcher_background">${background}</color></resources>\n`));
for (const name of ['ic_launcher', 'ic_launcher_round']) {
  output.set(`${res}/mipmap-anydpi-v26/${name}.xml`, Buffer.from(`<?xml version="1.0" encoding="utf-8"?>\n<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n  <background android:drawable="@color/ic_launcher_background"/>\n  <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n  <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>\n</adaptive-icon>\n`));
}
const splashSizes = {
  drawable: [480, 320],
  'drawable-port-mdpi': [320, 480], 'drawable-port-hdpi': [480, 800],
  'drawable-port-xhdpi': [720, 1280], 'drawable-port-xxhdpi': [960, 1600], 'drawable-port-xxxhdpi': [1280, 1920],
  'drawable-land-mdpi': [480, 320], 'drawable-land-hdpi': [800, 480],
  'drawable-land-xhdpi': [1280, 720], 'drawable-land-xxhdpi': [1600, 960], 'drawable-land-xxxhdpi': [1920, 1280],
};
for (const [folder, [width, height]] of Object.entries(splashSizes)) {
  const size = Math.round(Math.min(width, height) * 0.25);
  const logo = await sharp(Buffer.from(svg)).resize(size, size).png().toBuffer();
  output.set(`${res}/${folder}/splash.png`, await sharp({ create: { width, height, channels: 4, background: '#F4F7F3' } }).composite([{ input: logo, gravity: 'center' }]).png().toBuffer());
}
let failures = 0;
for (const [relative, content] of output) {
  const target = path.join(root, relative);
  if (check) {
    const actual = await readFile(target).catch(() => null);
    let matches = actual?.equals(content) ?? false;
    // Git may check text assets out with CRLF on Windows; line endings are not design drift.
    if (actual && !relative.endsWith('.png') && !matches) {
      matches = actual.toString('utf8').replace(/\r\n/g, '\n') === content.toString('utf8').replace(/\r\n/g, '\n');
    }
    // PNG encoders can differ across operating systems; compare actual pixels.
    if (actual && relative.endsWith('.png') && !matches) {
      const a = await sharp(actual).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
      const b = await sharp(content).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
      matches = a.info.width === b.info.width && a.info.height === b.info.height && a.data.equals(b.data);
    }
    if (!matches) { console.error(`STALE ${relative}`); failures++; }
  } else {
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, content);
  }
}
if (failures) throw new Error(`${failures} brand assets are stale. Run npm run brand:generate.`);
console.log(`BRAND_${check ? 'CHECK' : 'GENERATE'}=PASS (${output.size} assets)`);
